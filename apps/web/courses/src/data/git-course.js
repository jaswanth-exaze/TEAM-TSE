function block(number, id, title, keyTopics, options = {}) {
  const hours = options.hours ?? 16
  return {
    number,
    id,
    title,
    category: `Block ${number}`,
    keyTopics,
    hours,
    badge: `${hours} hours`,
    capstone: options.capstone || '',
    notes: options.notes || '',
    studyFiles: options.studyFiles || [],
    syllabusOnly: true,
  }
}

